from roadmapper.agents.utils import calculate_degree_and_depth


ITEM_ID_KEY = "id"
PROCESS_RESULT_KEY = "process_result"
IS_PROCESS_SUCCESS_KEY = "is_success"
ITEM_JSON_DETAIL_DIR = "item_json_detail"
PROCESS_LOG_FILE_NAME = "process.log"
RECOVER_REMARK_FILE_NAME = "recover_remark.md"
PROCESS_MERGED_RESULT_FILE_NAME = "merged_result.json"
ITEM_FAIL_MAP_FILE_NAME = "item_fail_map.json"
RUNTIME_INFO_FILE_NAME = "runtime_info.md"
EVALUATION_RESULT_KEY_FILE_NAME = "evaluation_result.json"
DATASET_REMARK_FILE_NAME = "dataset_remark.md"


class Config:
    """Configuration class"""

    def __init__(self):
        self.dataset_file = ""
        self.restore_from_dir = ""
        self.output_root_dir = "output"
        self.model_name = "qwen/qwen3-32b"
        self.model_client = AsyncOpenAI(
            api_key="",
            base_url=""
        )
        self.rpm = 600
        self.process_count = -1
        self.max_retry_count_per_item = 50
        self.shuffle = False
        self.max_processing_count = 800
        self.golden_roadmap_dir = "../data/golden-roadmap"


class TaskManager:
    """Task manager"""

    async def process_one_item(self, item: Any):
        """Process a data item using the specified worker"""
        raw_item = item.copy()
        item_id = item[ITEM_ID_KEY]
        self.processing_items.append(item_id)
        try:
            # ============================ Processing logic for each data item starts ============================
            def EvaluateOneItem(model_output_roadmap: str, golden_roadmap: str) -> tuple:
                """Calculate scores for model roadmap and golden roadmap in 'degree' and 'depth' dimensions"""
                model_output_degree, model_output_depth = calculate_degree_and_depth(
                    model_output_roadmap
                )
                golden_degree, golden_depth = calculate_degree_and_depth(golden_roadmap)

                degree_score = 1 - (abs(model_output_degree - golden_degree) / golden_degree)
                depth_score = 1 - (abs(model_output_depth - golden_depth) / golden_depth)

                # Round and adjust range to 0-100
                degree_score = round(degree_score * 100)
                depth_score = round(depth_score * 100)
                return degree_score, depth_score
            
            # Read golden roadmap
            golden_roadmap_file_path = os.path.join(self.config.golden_roadmap_dir, f"{item_id}.md")
            with open(golden_roadmap_file_path, "r", encoding="utf-8") as f:
                golden_roadmap = f.read()

            # Construct evaluation prompt
            evaluate_prompt = f"""<<Research Problem>>
{item["core_research_question"]}

<<Golden Roadmap>>
{golden_roadmap}

<<Model-Generated Roadmap>>
{item["roadmap"]}

The <<Research Problem>> above is a challengeable research problem.
The <<Golden Roadmap>> is the step-by-step roadmap for solving the problem annotated by human experts and serves as the standard answer.
The <<Model-Generated Roadmap>> is the roadmap generated by the model for solving the <<Research Problem>>.
You are a fair and objective evaluation expert, focusing on multi-dimensional evaluation of the <<Model-Generated Roadmap>> based on the <<Golden Roadmap>>.

Please strictly follow these requirements:
1. There are two evaluation metrics: the key step representation score (step_score) and the logical coherence score (logic_score), each scored from 0 to 100.

2. step_score metric: In the <<Golden Roadmap>>, actions marked with <key_step> are regarded as key steps. The step_score metric mainly evaluates how well these key steps are represented in the <<Model-Generated Roadmap>>; the more key steps are covered, the higher the score.
   - 0-20 points: Almost none of the key steps are represented, or there is a severe deviation.
   - 21-40 points: Only a small number of key steps are represented, but most are missing.
   - 41-60 points: About half of the key steps are represented, with notable omissions.
   - 61-80 points: Most key steps are represented, with only a few omissions.
   - 81-100 points: Almost all or all key steps are comprehensively represented.

3. logic_score metric: This primarily evaluates the alignment between the main ideas of the <<Model-Generated Roadmap>> and <<Golden Roadmap>>. The more coherent the logic and the better the alignment, the higher the score.
   - 0-20 points: The logic is chaotic, and the main idea does not align at all with the reference answer.
   - 21-40 points: There are many logical issues, and the alignment with the reference answer is low.
   - 41-60 points: The logic is basically coherent, with some alignment with the reference answer.
   - 61-80 points: The logic is relatively coherent, and the alignment with the reference answer is high.
   - 81-100 points: The logic is highly coherent, and the main idea is very well aligned with the reference answer.

Output Format Requirements:
You must answer in English and enclose your step_score within <step_score> tags, your logic_score within <logic_score> tags, and your detailed reasoning within <eval_reason> tags. For example:

<step_score>67</step_score>
<logic_score>73</logic_score>
<eval_reason>Your detailed analysis covering the key step representation and logical coherence...</eval_reason>

Please strictly follow the requirements above and provide the output in the specified format."""

            response = await self.config.model_client.chat.completions.create(
                model=self.config.model_name,
                messages=[{"role": "user", "content": evaluate_prompt}],
            )

            # Extract and parse model returned scoring results
            model_content = response.choices[0].message.content
            step_score_match = re.search(r"<step_score>\s*(\d+)\s*</step_score>", model_content, re.DOTALL)
            logic_score_match = re.search(r"<logic_score>\s*(\d+)\s*</logic_score>", model_content, re.DOTALL)
            eval_reason_match = re.search(r"<eval_reason>\s*(.*?)\s*</eval_reason>", model_content, re.DOTALL)
            if not step_score_match:
                raise ValueError(f"Failed to parse model output [step_score]: {model_content}")
            if not logic_score_match:
                raise ValueError(f"Failed to parse model output [logic_score]: {model_content}")
            if not eval_reason_match:
                raise ValueError(f"Failed to parse model output [eval_reason]: {model_content}")
            step_score = int(step_score_match.group(1))
            logic_score = int(logic_score_match.group(1))
            eval_reason = eval_reason_match.group(1).strip() if eval_reason_match else ""

            # Calculate degree and depth scores
            degree_score, depth_score = EvaluateOneItem(
                item["roadmap"], golden_roadmap
            )
            item["evaluation_result"] = {
                "step_score": step_score,
                "logic_score": logic_score,
                "degree_score": degree_score,
                "depth_score": depth_score,
                "eval_reason": eval_reason,
            }
            # ============================ Processing logic for each data item ends ============================

            self.success_items.append(item_id)
            item[PROCESS_RESULT_KEY] = {IS_PROCESS_SUCCESS_KEY: True}
            self.save_item_result(item)
        except Exception as e:
            item[PROCESS_RESULT_KEY] = {IS_PROCESS_SUCCESS_KEY: False, "error": str(e)}
            self.save_item_result(item)
            self.item_fail_map[item_id] += 1
            if self.item_fail_map[item_id] > self.config.max_retry_count_per_item:
                self.logger.error(
                    f"Item {item_id} failed after {self.config.max_retry_count_per_item} retries, giving up."
                )
                self.stop_schedule = True
                return
            self.data_queue.append(raw_item)
            self.logger.error(f"Item {item_id} failed with error: {e}")
        finally:
            if item_id in self.processing_items:
                self.processing_items.remove(item_id)

    def __init__(
        self,
        config: Config,
    ):
        self.config = config
        self.dataset = None
        self.data_queue = deque[Any]()
        self.success_items = []
        self.processing_items = []
        self.item_fail_map = {}
        self.stop_schedule = False
        self.is_restore_from_dir = bool(self.config.restore_from_dir)
        self.active_tasks = []

        with open(self.config.dataset_file, "r") as f:
            self.dataset = json.load(f)
            self.dataset = (
                self.dataset[: self.config.process_count]
                if self.config.process_count > 0
                else self.dataset
            )
            if self.config.shuffle:
                random.shuffle(self.dataset)
            self.total_count = len(self.dataset)

        self.current_run_output_dir = self.create_output_dir(self.config)

        if self.is_restore_from_dir:
            self.restore_from_dir()
        else:
            for item in self.dataset:
                self.data_queue.append(item)
                self.item_fail_map[item[ITEM_ID_KEY]] = 0

        self.logger = self.setup_logging()

    def restore_from_dir(self):
        """Restore running state from existing output directory"""
        restore_dir = self.config.restore_from_dir
        if not os.path.isdir(restore_dir):
            raise ValueError(f"restore_from_dir path does not exist: {restore_dir}")

        shutil.copytree(restore_dir, self.current_run_output_dir, dirs_exist_ok=True)

        # Read completed results
        processed_item_ids = set()
        item_json_detail_dir = os.path.join(
            self.current_run_output_dir, ITEM_JSON_DETAIL_DIR
        )
        if os.path.isdir(item_json_detail_dir):
            item_json_detail_files = [
                fname
                for fname in os.listdir(item_json_detail_dir)
                if fname.endswith(".json")
            ]
            for fname in item_json_detail_files:
                fpath = os.path.join(item_json_detail_dir, fname)
                with open(fpath, "r", encoding="utf-8") as f:
                    item = json.load(f)
                item_id = item.get(ITEM_ID_KEY)
                is_success = item.get(PROCESS_RESULT_KEY, {}).get(
                    IS_PROCESS_SUCCESS_KEY
                )
                if item_id is not None and is_success:
                    processed_item_ids.add(item_id)
        else:
            self.logger.warning(
                f"Item JSON detail directory not found, treating as no completed data, directory: {item_json_detail_dir}"
            )

        # Generate queue and success list based on dataset
        for item in self.dataset:
            item_id = item.get(ITEM_ID_KEY)
            if item_id in processed_item_ids:
                self.success_items.append(item_id)
            else:
                self.data_queue.append(item)
                self.item_fail_map[item_id] = 0

        # Record recovery information for tracking
        remark_path = os.path.join(
            self.current_run_output_dir, RECOVER_REMARK_FILE_NAME
        )
        with open(remark_path, "w", encoding="utf-8") as f:
            now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
            left_ids = [item.get(ITEM_ID_KEY) for item in self.data_queue]
            f.write(
                f"Time: {now_str}\n"
                f"Restored from: {restore_dir}\n"
                f"New output dir: {self.current_run_output_dir}\n"
                f"Completed items count: {len(self.success_items)}\n"
                f"Remaining items count: {len(self.data_queue)}\n"
                f"Remaining items: {', '.join(left_ids) if left_ids else '(empty)'}\n"
            )

    def can_enqueue(self) -> bool:
        """Check if items can be enqueued"""
        return (
            len(self.processing_items) <= self.config.max_processing_count
            if self.config.max_processing_count > 0
            else True
        )

    def setup_logging(self):
        """Setup logging"""
        # Set logging level for openai and httpx to WARNING to avoid excessive HTTP request logs
        logging.getLogger("httpx").setLevel(logging.WARNING)
        logging.getLogger("openai").setLevel(logging.WARNING)

        log_file_path = os.path.join(self.current_run_output_dir, PROCESS_LOG_FILE_NAME)
        logging.basicConfig(
            level=logging.INFO,
            format="%(asctime)s - %(levelname)s - %(message)s",
            handlers=[
                logging.FileHandler(log_file_path, encoding="utf-8"),
                logging.StreamHandler(),
            ],
        )
        return logging.getLogger(__name__)

    def create_output_dir(self, config: Config) -> str:
        """Create output directory named with timestamp and processing data count"""
        timestamp = datetime.now().strftime("%Y-%m-%d-%H-%M-%S")
        # Extract the last part of model name
        model_name_part = config.model_name.split("/")[-1]
        output_dir = os.path.join(
            config.output_root_dir,
            config.dataset_file.split("/")[-1].split(".")[0],
            model_name_part,
            f"{timestamp}_process_count_{self.total_count}",
        )
        os.makedirs(output_dir, exist_ok=True)
        os.makedirs(os.path.join(output_dir, ITEM_JSON_DETAIL_DIR), exist_ok=True)
        return output_dir

    def save_item_result(self, item: Any):
        """Save result"""
        with open(
            os.path.join(
                self.current_run_output_dir,
                ITEM_JSON_DETAIL_DIR,
                f"{item[ITEM_ID_KEY]}.json",
            ),
            "w",
            encoding="utf-8",
        ) as f:
            json.dump(item, f, indent=4, ensure_ascii=False)

    def merge_all_item_results(self):
        """After all items are processed, merge all item results into a json list file sorted by filename"""
        item_json_detail_dir = os.path.join(
            self.current_run_output_dir, ITEM_JSON_DETAIL_DIR
        )
        # Get all json filenames and sort by filename
        file_list = sorted(
            [f for f in os.listdir(item_json_detail_dir) if f.endswith(".json")]
        )
        merged_items = []
        for fname in file_list:
            fpath = os.path.join(item_json_detail_dir, fname)
            with open(fpath, "r", encoding="utf-8") as f:
                item = json.load(f)
                merged_items.append(item)
        # Save merged results
        merged_file_path = os.path.join(
            self.current_run_output_dir, PROCESS_MERGED_RESULT_FILE_NAME
        )
        with open(merged_file_path, "w", encoding="utf-8") as f:
            json.dump(merged_items, f, indent=4, ensure_ascii=False)

        # Calculate average scores
        success_items = [
            item
            for item in merged_items
            if item.get(PROCESS_RESULT_KEY, {}).get(IS_PROCESS_SUCCESS_KEY, False)
        ]

        if success_items:
            average_step_score = sum(
                item["evaluation_result"]["step_score"] for item in success_items
            ) / len(success_items)
            average_logic_score = sum(
                item["evaluation_result"]["logic_score"] for item in success_items
            ) / len(success_items)
            average_degree_score = sum(
                item["evaluation_result"]["degree_score"] for item in success_items
            ) / len(success_items)
            average_depth_score = sum(
                item["evaluation_result"]["depth_score"] for item in success_items
            ) / len(success_items)

            overall_average_score = (
                average_step_score
                + average_logic_score
                + average_degree_score
                + average_depth_score
            ) / 4

            # Print to console
            print(f"Average step score: {average_step_score:.2f}")
            print(f"Average logic score: {average_logic_score:.2f}")
            print(f"Average degree score: {average_degree_score:.2f}")
            print(f"Average depth score: {average_depth_score:.2f}")
            print(f"Average score: {overall_average_score:.2f}")

            # Save to evaluation result file
            evaluation_result = {
                "average_step_score": round(average_step_score, 2),
                "average_logic_score": round(average_logic_score, 2),
                "average_degree_score": round(average_degree_score, 2),
                "average_depth_score": round(average_depth_score, 2),
                "average_score": round(overall_average_score, 2),
            }
            evaluation_result_file_path = os.path.join(
                self.current_run_output_dir, EVALUATION_RESULT_KEY_FILE_NAME
            )
            with open(evaluation_result_file_path, "w", encoding="utf-8") as f:
                json.dump(evaluation_result, f, indent=4, ensure_ascii=False)

        # Save dataset file full path for subsequent tracking
        dataset_remark_path = os.path.join(
            self.current_run_output_dir, DATASET_REMARK_FILE_NAME
        )
        dataset_full_path = (
            os.path.abspath(self.config.dataset_file)
            if self.config.dataset_file
            else "(empty)"
        )
        with open(dataset_remark_path, "w", encoding="utf-8") as f:
            f.write(f"Dataset file: {dataset_full_path}\n")

    def save_runtime_info(self):
        """Save current runtime information to file"""
        # Save item_fail_map to file
        item_fail_map_file_path = os.path.join(
            self.current_run_output_dir, ITEM_FAIL_MAP_FILE_NAME
        )
        with open(item_fail_map_file_path, "w", encoding="utf-8") as f:
            json.dump(self.item_fail_map, f, indent=4, ensure_ascii=False)

        queue_item_ids = [item[ITEM_ID_KEY] for item in self.data_queue]

        # Find all items with failure count equal to maximum count
        max_failed_items = "(empty)"
        max_fail_count = 0
        if self.item_fail_map:
            max_fail_count = max(self.item_fail_map.values())
            if max_fail_count > 0:
                max_failed_item_list = [
                    f"{item_id}"
                    for item_id, fail_count in self.item_fail_map.items()
                    if fail_count == max_fail_count
                ]
                max_failed_items = ", ".join(max_failed_item_list)

        detail_info = f"**Success count**: {len(self.success_items)};\n"
        detail_info += f"**Processing count**: {len(self.processing_items)};\n"
        detail_info += f"**Total count**: {self.total_count};\n\n"
        detail_info += f"**Success items**: {', '.join(map(str, self.success_items)) if self.success_items else '(empty)'}\n\n"
        detail_info += f"**Processing items**: {', '.join(map(str, self.processing_items)) if self.processing_items else '(empty)'}\n\n"
        detail_info += f"**Queue items**: {', '.join(queue_item_ids) if queue_item_ids else '(empty)'}\n\n"
        detail_info += f"**Max Failed Count**: {max_fail_count}\n\n"
        detail_info += f"**Max Failed Items**: {max_failed_items}\n\n"
        runtime_info_file_path = os.path.join(
            self.current_run_output_dir, RUNTIME_INFO_FILE_NAME
        )
        with open(runtime_info_file_path, "w", encoding="utf-8") as f:
            f.write(detail_info)

    def copy_current_file(self):
        """Copy current Python file to output directory"""
        current_file_path = __file__
        copied_file_path = os.path.join(
            self.current_run_output_dir, os.path.basename(current_file_path)
        )
        shutil.copy2(current_file_path, copied_file_path)
        self.logger.info(f"Python file copied to {copied_file_path}")

    async def main_schedule(self):
        """Run task manager"""
        self.logger.info("Task manager started.")
        if self.is_restore_from_dir:
            self.logger.info(f"Restored from: {self.config.restore_from_dir}")
            self.logger.info(
                f"Completed: {len(self.success_items)}, Remaining: {len(self.data_queue)}"
            )

        self.copy_current_file()

        with tqdm(total=self.total_count, initial=len(self.success_items)) as pbar:
            last_success = len(self.success_items)
            while len(self.success_items) < self.total_count and not self.stop_schedule:
                await asyncio.sleep(60 / self.config.rpm)

                if self.data_queue and self.can_enqueue():
                    self.active_tasks.append(
                        asyncio.create_task(
                            self.process_one_item(self.data_queue.popleft())
                        )
                    )

                self.active_tasks = [t for t in self.active_tasks if not t.done()]
                pbar.update(len(self.success_items) - last_success)
                last_success = len(self.success_items)
                self.save_runtime_info()

        self.active_tasks = [t for t in self.active_tasks if not t.done()]
        if self.active_tasks:
            self.logger.info(
                f"Waiting for {len(self.active_tasks)} active tasks to complete..."
            )
            await asyncio.gather(*self.active_tasks, return_exceptions=True)
            self.logger.info("All active tasks completed.")

        self.merge_all_item_results()
        self.save_runtime_info()
        self.logger.info(
            f"Task manager finished. Success: {len(self.success_items)}/{self.total_count}"
        )
        self.logger.info(f"Output directory: {self.current_run_output_dir}")


async def main():
    """Main function, override dataset file and model name via command line only"""
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--dataset-file",
        type=str,
        default=None,
    )
    parser.add_argument(
        "--model-name",
        type=str,
        default=None,
    )

    args = parser.parse_args()

    config = Config()
    if args.dataset_file:
        config.dataset_file = args.dataset_file
    if args.model_name:
        config.model_name = args.model_name

    manager = TaskManager(config)
    await manager.main_schedule()


if __name__ == "__main__":
    asyncio.run(main())
